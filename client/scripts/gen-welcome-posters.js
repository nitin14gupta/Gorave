// Writes src/constants/welcomePosters.ts from the files in
// assets/images/welcome, so adding a poster is: drop the file in, then run
//   npm run posters
const fs = require('fs')
const path = require('path')

const dir = path.join(__dirname, '..', 'assets', 'images', 'welcome')
const out = path.join(__dirname, '..', 'src', 'constants', 'welcomePosters.ts')

const files = fs.readdirSync(dir).filter(f => /\.(webp|png|jpe?g)$/i.test(f)).sort()
const lines = files.map(f => `  require('../../assets/images/welcome/${f}'),`)
fs.writeFileSync(
  out,
  `// Generated by scripts/gen-welcome-posters.js from assets/images/welcome.\n` +
  `// Don't edit by hand: drop images in that folder and run \`npm run posters\`.\n` +
  `export const WELCOME_POSTERS: number[] = [\n${lines.join('\n')}\n]\n`,
)
console.log(`welcomePosters.ts: ${files.length} posters`)
